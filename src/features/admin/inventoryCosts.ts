function round2(n: number): number {
  return Math.round((n + Number.EPSILON) * 100) / 100;
}

function sphereWeightG(sizeMm: number, densityGPerCm3: number, shapeFactor = 1): number {
  const radiusMm = sizeMm / 2;
  const volumeCm3 = (4 / 3) * Math.PI * radiusMm ** 3 / 1000;
  return volumeCm3 * densityGPerCm3 * shapeFactor;
}

