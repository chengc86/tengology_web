export function calculateInventoryLot(input: InventoryCostLotInput): InventoryCostLot {
  const shippingCnyPerStrand = round2((input.estimatedWeightGPerStrand / 1000) * SHIPPING_RATE_CNY_PER_KG);
  const totalCostCnyPerStrand = round2(input.unitPurchasePriceCny + shippingCnyPerStrand);
  const unitCostCnyPerBead = round2(totalCostCnyPerStrand / input.beadsPerStrand);
  const totalPurchasePriceCny = round2(input.unitPurchasePriceCny * input.purchaseQuantity);
  const totalShippingCny = round2(shippingCnyPerStrand * input.purchaseQuantity);
  const totalLandedCostCny = round2(totalCostCnyPerStrand * input.purchaseQuantity);
  const totalBeads = input.beadsPerStrand * input.purchaseQuantity;

  return {
    ...input,
    shippingCnyPerStrand,
    totalCostCnyPerStrand,
    unitCostCnyPerBead,
    totalPurchasePriceCny,
    totalShippingCny,
    totalLandedCostCny,
    totalBeads,
  };
}

export const inventoryCostLots = inventoryCostLotInputs.map(calculateInventoryLot);
